<?php

namespace App\Http\Controllers;

use App\Models\Food;
use App\Models\Claim;
use Illuminate\Http\Request;

class ClaimController extends Controller
{
    /**
     * Simpan claim makanan
     */
    public function store(Request $request, Food $food)
    {
        /*
        |--------------------------------------------------------------------------
        | HANYA PENERIMA
        |--------------------------------------------------------------------------
        */

        if (auth()->user()->role !== 'penerima') {

            abort(403, 'Hanya penerima yang dapat claim makanan');

        }

        /*
        |--------------------------------------------------------------------------
        | VALIDASI
        |--------------------------------------------------------------------------
        */

        $request->validate([

            'quantity' => 'required|integer|min:1',

            'notes' => 'nullable|string|max:1000'

        ]);

        /*
        |--------------------------------------------------------------------------
        | CEK STATUS MAKANAN
        |--------------------------------------------------------------------------
        */

        if ($food->status !== 'tersedia') {

            return back()->with(

                'error',
                'Makanan tidak tersedia untuk di-claim'

            );

        }

        /*
        |--------------------------------------------------------------------------
        | CEK STOK
        |--------------------------------------------------------------------------
        */

        if ($food->quantity <= 0) {

            return back()->with(

                'error',
                'Stok makanan sudah habis'

            );

        }

        /*
        |--------------------------------------------------------------------------
        | CEK QUANTITY CLAIM
        |--------------------------------------------------------------------------
        */

        if ($request->quantity > $food->quantity) {

            return back()->with(

                'error',
                'Jumlah claim melebihi stok makanan'

            );

        }

        /*
        |--------------------------------------------------------------------------
        | SIMPAN CLAIM
        |--------------------------------------------------------------------------
        */

        Claim::create([

            'food_id' => $food->id,

            'user_id' => auth()->id(),

            'quantity' => $request->quantity,

            'status' => 'pending',

            'claim_date' => now(),

            'notes' => $request->notes

        ]);

        /*
        |--------------------------------------------------------------------------
        | KURANGI STOK MAKANAN
        |--------------------------------------------------------------------------
        */

        $food->quantity -= $request->quantity;

        /*
        |--------------------------------------------------------------------------
        | UPDATE STATUS MAKANAN
        |--------------------------------------------------------------------------
        */

        if ($food->quantity <= 0) {

            $food->status = 'habis';

        } else {

            $food->status = 'tersedia';

        }

        /*
        |--------------------------------------------------------------------------
        | SIMPAN
        |--------------------------------------------------------------------------
        */

        $food->save();

        /*
        |--------------------------------------------------------------------------
        | REDIRECT
        |--------------------------------------------------------------------------
        */

        return redirect()
            ->route('foods.index')
            ->with('success', 'Makanan berhasil di-claim');
    }

    /**
     * History claim penerima
     */
    public function myClaims()
    {
        /*
        |--------------------------------------------------------------------------
        | HANYA PENERIMA
        |--------------------------------------------------------------------------
        */

        if (auth()->user()->role !== 'penerima') {

            abort(403, 'Akses ditolak');

        }

        /*
        |--------------------------------------------------------------------------
        | AMBIL DATA CLAIM
        |--------------------------------------------------------------------------
        */

        $claims = Claim::with('food')

            ->where('user_id', auth()->id())

            ->latest()

            ->paginate(10);

        /*
        |--------------------------------------------------------------------------
        | VIEW
        |--------------------------------------------------------------------------
        */

        return view(

            'claims.my-claims',

            compact('claims')

        );
    }

    /**
     * Claim masuk penyedia
     */
    public function incomingClaims()
    {
        /*
        |--------------------------------------------------------------------------
        | HANYA PENYEDIA
        |--------------------------------------------------------------------------
        */

        if (auth()->user()->role !== 'penyedia') {

            abort(403, 'Akses ditolak');

        }

        /*
        |--------------------------------------------------------------------------
        | AMBIL CLAIM MAKANAN MILIK PENYEDIA
        |--------------------------------------------------------------------------
        */

        $claims = Claim::with(['food', 'user'])

            ->whereHas('food', function ($query) {

                $query->where(

                    'user_id',

                    auth()->id()

                );

            })

            ->latest()

            ->paginate(10);

        /*
        |--------------------------------------------------------------------------
        | VIEW
        |--------------------------------------------------------------------------
        */

        return view(

            'claims.incoming-claims',

            compact('claims')

        );
    }

    /**
     * Approve claim
     */
    public function approve(Claim $claim)
    {
        /*
        |--------------------------------------------------------------------------
        | HANYA PENYEDIA
        |--------------------------------------------------------------------------
        */

        if (auth()->user()->role !== 'penyedia') {

            abort(403);

        }

        /*
        |--------------------------------------------------------------------------
        | VALIDASI OWNER MAKANAN
        |--------------------------------------------------------------------------
        */

        if ($claim->food->user_id !== auth()->id()) {

            abort(403);

        }

        /*
        |--------------------------------------------------------------------------
        | UPDATE STATUS
        |--------------------------------------------------------------------------
        */

        $claim->status = 'disetujui';

        $claim->save();

        /*
        |--------------------------------------------------------------------------
        | REDIRECT
        |--------------------------------------------------------------------------
        */

        return back()->with(

            'success',

            'Claim berhasil disetujui'

        );
    }

    /**
     * Reject claim
     */
    public function reject(Claim $claim)
    {
        /*
        |--------------------------------------------------------------------------
        | HANYA PENYEDIA
        |--------------------------------------------------------------------------
        */

        if (auth()->user()->role !== 'penyedia') {

            abort(403);

        }

        /*
        |--------------------------------------------------------------------------
        | VALIDASI OWNER MAKANAN
        |--------------------------------------------------------------------------
        */

        if ($claim->food->user_id !== auth()->id()) {

            abort(403);

        }

        /*
        |--------------------------------------------------------------------------
        | UPDATE STATUS CLAIM
        |--------------------------------------------------------------------------
        */

        $claim->status = 'ditolak';

        $claim->save();

        /*
        |--------------------------------------------------------------------------
        | KEMBALIKAN STOK MAKANAN
        |--------------------------------------------------------------------------
        */

        $food = $claim->food;

        $food->quantity += $claim->quantity;

        /*
        |--------------------------------------------------------------------------
        | UPDATE STATUS MAKANAN
        |--------------------------------------------------------------------------
        */

        if ($food->quantity > 0) {

            $food->status = 'tersedia';

        }

        $food->save();

        /*
        |--------------------------------------------------------------------------
        | REDIRECT
        |--------------------------------------------------------------------------
        */

        return back()->with(

            'success',

            'Claim berhasil ditolak'

        );
    }
}